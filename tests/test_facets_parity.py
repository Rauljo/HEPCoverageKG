def test_a_second_vocabulary_version_is_actually_written(tmp_path):
    """`vocabulary` exists so two versions can coexist and be diffed. The first
    implementation parameterised the DELETE but hardcoded the version in the
    INSERT, so asking for v2 reported "4594 rows" and wrote none of them --
    a silent no-op that looked like success."""
    import shutil

    src = Path("data/processed/hepkg.db")
    if not src.exists():
        pytest.skip("no pilot database")
    db = tmp_path / "two-vocabs.db"
    shutil.copy(src, db)
    conn = facets_derive.connect(db)

    facets_derive.derive_facets(conn, vocabulary="facets-v1")
    facets_derive.derive_facets(conn, vocabulary="facets-test")
    counts = dict(conn.execute(
        "SELECT vocabulary, COUNT(*) FROM entity_facet GROUP BY vocabulary"))
    assert counts.get("facets-test"), "the requested vocabulary was never written"
    assert counts["facets-test"] == counts["facets-v1"]
    # and re-deriving one version must not disturb the other
    facets_derive.derive_facets(conn, vocabulary="facets-v1")
    assert dict(conn.execute(
        "SELECT vocabulary, COUNT(*) FROM entity_facet GROUP BY vocabulary")) == counts
