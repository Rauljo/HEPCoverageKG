def test_port_agrees_with_upstream_on_every_leaf(upstream_signatures):
    """Our port takes SQLite rows, upstream's takes pydantic models. Same rules,
    so same verdict on every candidate — this is what makes the port
    trustworthy, and the only thing that will catch it drifting."""
    upstream = upstream_signatures
    conn = _real_db()

    checked = 0
    for cut in signatures.cuts_from_db(conn):
        ours = signatures.synthesize_signature(cut)

        predicate = next(
            (p for p in upstream._COUNT_PREDICATES if p.value == cut.predicate), None)

        class _A:  # duck-typed to the fields upstream's function reads
            signature = None
            object_id = cut.object_id
            qualifiers = cut.qualifiers

        _A.predicate = predicate
        theirs = upstream.synthesize_signature(_A())
        checked += 1

        if ours is None:
            assert theirs is None, f"{cut.assertion_id}: we declined, upstream did not"
        else:
            assert theirs is not None, f"{cut.assertion_id}: upstream declined, we did not"
            assert ours["comparator"] == theirs.comparator, cut.assertion_id
            assert ours["value"] == theirs.value, cut.assertion_id
            assert ours["range_max"] == theirs.range_max, cut.assertion_id
            assert ours["object_ref"] == theirs.object_ref, cut.assertion_id

    assert checked > 1000, "expected the whole candidate set, got a suspiciously small sample"


def test_port_agrees_with_upstream_on_the_or_grouping(upstream_signatures):
    """The OR rule is the one with real consequences — reading an AND as an OR
    makes a region look looser than it is and nothing downstream can tell."""
    upstream = upstream_signatures
    conn = _real_db()
    cuts = signatures.cuts_from_db(conn)

    theirs_input = []
    for cut in cuts:
        predicate = next(
            (p for p in upstream._COUNT_PREDICATES if p.value == cut.predicate), None)

        class _A:
            signature = None
            object_id = cut.object_id
            qualifiers = cut.qualifiers
            subject_id = cut.subject_id
            assertion_id = cut.assertion_id

        _A.predicate = predicate
        theirs_input.append(_A())

    ours = signatures.synthesize_or_groups(cuts)
    theirs = upstream.synthesize_or_groups(theirs_input)
    assert set(ours) == set(theirs)
    for assertion_id, tree in ours.items():
        mirror = theirs[assertion_id]
        assert mirror.operator.value == tree["operator"]
        assert len(mirror.children) == len(tree["children"])


def test_facet_functions_agree_with_upstream_on_every_label(upstream_vocabulary):
    """Every label in the graph, through both copies of the tables. Redundant
    while the vendored file is byte-identical — and the guard that catches it
    when it stops being.

    Runs over `entity_occurrence`, the labels the derivation actually sees.
    """
    upstream = upstream_vocabulary
    conn = _real_db()
    checked = 0
    for row in conn.execute("SELECT DISTINCT kind, label FROM entity_occurrence"):
        kind, label = row["kind"], row["label"]
        assert facet_tags(kind, label) == upstream.facet_tags(kind, label), label
        assert canonicalize_entity(kind, label) == upstream.canonicalize_entity(kind, label), label
        checked += 1
    assert checked > 1000, "expected every distinct label, got a suspiciously small sample"


# --- the prompt must not contain the answers -----------------------------------


def test_no_facet_value_leaks_into_the_schema_card():
    """The card lists field NAMES and coverage, never values.

    An earlier version listed every value in every field, and the values that
    read as most natural to include were five of the seven distinct keys in the
    supervisor's Tier 1 gold answers. A Tier 1 score under that card would have
    been partly measuring the prompt (D-054). This is the regression guard: it
    fails the moment anyone adds "a couple of examples".
    """
    from hepcoveragekg.query import schema_card

    conn = _real_db()
    facets_derive.derive_facets(conn)
    card = schema_card.render(conn)

    values = {r["value"] for r in conn.execute("SELECT DISTINCT value FROM entity_facet")}
    # Keys short enough to collide with ordinary English or with the notation
    # block are excluded: `MET` is a standard physics abbreviation the prompt
    # has always explained, and the coincidence with a facet key is not
    # something the card introduced.
    checkable = {v for v in values if len(v) > 4 and v not in {"Track", "Jet"}}
    leaked = sorted(v for v in checkable if v in card)
    assert not leaked, f"facet values present in the schema card: {leaked}"


